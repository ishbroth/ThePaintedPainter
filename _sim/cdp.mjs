import { spawn } from 'node:child_process';
import fs from 'node:fs';
const CH = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const chrome = spawn(CH, ['--headless=new', '--disable-gpu', '--remote-debugging-port=9333', '--window-size=1200,1000', '--user-data-dir=' + process.env.TEMP + '/cdp-prof', 'about:blank'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 3500));
const tabs = await (await fetch('http://127.0.0.1:9333/json')).json();
const ws = new WebSocket(tabs.find((t) => t.type === 'page').webSocketDebuggerUrl);
await new Promise((r) => (ws.onopen = r));
let id = 0; const pending = new Map();
ws.onmessage = (m) => { const d = JSON.parse(m.data); if (d.id && pending.has(d.id)) { pending.get(d.id)(d.result); pending.delete(d.id); } };
const send = (method, params = {}) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params })); });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const shot = async (name) => { const r = await send('Page.captureScreenshot', { format: 'png' }); fs.writeFileSync('_sim/shots/' + name + '.png', Buffer.from(r.data, 'base64')); };
const ev = async (expr) => (await send('Runtime.evaluate', { expression: expr, returnByValue: true })).result?.value;
await send('Page.enable'); await send('Page.navigate', { url: 'http://localhost:4173/' }); await sleep(3500);
await ev("document.querySelector('.chat-estimator-section').scrollIntoView({block:'start'})"); await sleep(800);
await ev("document.querySelector('.chat-composer').click()"); await sleep(300);
await send('Input.insertText', { text: 'my master bedroom, about 14 by 16 and I would like the walls and ceiling painted' }); await sleep(300);
await shot('typing');
console.log('focused:', await ev("document.activeElement && document.activeElement.className"), '| text:', await ev("document.querySelector('.chat-composer-text').textContent.length"), '| send disabled:', await ev("document.querySelector('.chat-send-inline').disabled"));
await send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13, text: '\r' });
await send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13 });
await sleep(9000);
console.log('bubbles:', await ev("document.querySelectorAll('.chat-bubble').length"), '| focused after reply:', await ev("document.activeElement && document.activeElement.className"));
await send('Input.insertText', { text: '14x16' }); await sleep(300);
await shot('after');
ws.close(); chrome.kill();
process.exit(0);
